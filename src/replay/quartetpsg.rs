//! Quartet PSG (`sqt.*`: the Atari ST sound driver of the YM2149 member of the Quartet family,
//! Rob Povey and Steve Wetherill, 1990; played by the Eagleplayer "Quartet PSG"), played by running
//! the module's own driver.
//!
//! A module is the original Atari 68000 sound driver with its music data (see
//! `fixround/spec/quartetpsg`). This replayer runs it in place, where the host loaded the file, on
//! the repo's 68000 core with the standard cycle table (`m68k_rc::cycles`), as the Riff Raff, Benn
//! Daglish SID and Mark II replayers do. What the Eagleplayer adds around the driver is reproduced
//! from the specification:
//! * the module check (section 1.1), and the patch walk over the driver's code (section 2): the
//!   status register words become no-operations, the song-end sites and the register site become
//!   calls into two host hooks, the Atari hardware test becomes a plain branch;
//! * the conversion of the 11 captured YM register bytes to Paula writes after every tick, in the
//!   two conversions of the player (mode 0 "Mad Max", the default, with a restart sequence of the
//!   voices that waits on the host Paula; mode 1 "meynaf", chosen with the player's configuration
//!   file), with the specification's cycle ledger;
//! * the start-up timeline, the tick, the subsong change and the song end (section 3).
//!
//! Nothing is embedded: the two noise buffers are generated by the rule of section 8, the pulse
//! waveforms and the volume tables are small constants of the specification.
//!
//! Choices where the specification is silent (all safe, none can panic or hang): a module whose
//! patch walk runs off the file, whose end lies past the file, whose subsong marker is missing or
//! at or past the end, or whose song-end call cannot reach the hook with a 16-bit displacement is
//! not recognised; a driver that runs more than a few million instructions in one call ends the
//! song and is not called again; a wait on the audio interrupt flags is bounded; a subsong count
//! of 0 is reported as the single subsong 0; the host volume, balance and voice switches are not
//! modelled (the factor is 64, as in the reference runs).
//!
//! The configuration file is looked for as the player does (a 4-byte file `WT` and a word 0 or 1),
//! in the file named by the environment variable `QUARTETPSG_CFG`, else
//! `~/.config/amigaplayer-rs/EP-Quartet_PSG.cfg`; without one the mode is 0.

