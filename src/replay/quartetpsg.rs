pub const OPEN: Open = Open { name: "Quartet PSG", detect, new };

/// Where the run's detection starts, in the reference's log clock (the engine's start phase).
const S0: u64 = crate::engine::START_PHASE;
/// Colour clocks between two ticks (the default 50 Hz timer).
const TICK: u64 = 70940;
/// The player's initialisation without the patch walk (noise generation included).
const C_INIT_FIXED: u64 = 3_678_493;

/// The Paula voice of each converter voice A, B, C and N in mode 0.
const PV: [usize; 4] = [0, 3, 2, 1];
/// Volume scaling, volume or period bookkeeping and location bookkeeping costs by Paula voice.
const CV: [u64; 4] = [163, 180, 187, 214];
const SV: [u64; 4] = [79, 110, 141, 149];
const SL: [u64; 4] = [95, 126, 157, 165];
/// Volume tables of the two modes.
const VT0: [u16; 16] = [0, 1, 2, 3, 4, 5, 7, 9, 12, 16, 21, 27, 34, 42, 52, 64];
const VT1: [u16; 16] = [0, 1, 1, 1, 2, 2, 3, 4, 6, 8, 11, 16, 23, 32, 45, 64];

/// Offsets in the buffer block (section 8).
const NOISE1: u32 = 0;
const NOISE2: u32 = 0x400;
const PULSE2: u32 = 0x4400;
const PULSE: u32 = 0x4402;
const EMPTY: u32 = 0x4404;
const BLOCK: u32 = 0x4408;

fn w16(d: &[u8], o: usize) -> Option<u16> {
    d.get(o..o.checked_add(2)?).map(|b| u16::from_be_bytes([b[0], b[1]]))
}

fn w32(d: &[u8], o: usize) -> Option<u32> {
    d.get(o..o.checked_add(4)?).map(|b| u32::from_be_bytes([b[0], b[1], b[2], b[3]]))
}

fn put16(d: &mut [u8], o: usize, v: u16) -> Option<()> {
    d.get_mut(o..o.checked_add(2)?)?.copy_from_slice(&v.to_be_bytes());
    Some(())
}

fn put32(d: &mut [u8], o: usize, v: u32) -> Option<()> {
    d.get_mut(o..o.checked_add(4)?)?.copy_from_slice(&v.to_be_bytes());
    Some(())
}

/// The module check (section 1.1).
fn detect(d: &[u8]) -> bool {
    check(d).is_some()
}

fn check(d: &[u8]) -> Option<()> {
    for o in [0usize, 4, 8, 12] {
        if w16(d, o)? != 0x6000 {
            return None;
        }
        let disp = w16(d, o + 2)? as i16;
        if disp <= 0 || disp & 1 != 0 {
            return None;
        }
    }
    if w16(d, 16)? != 0x49FA {
        return None;
    }
    let t = 10 + w16(d, 10)? as usize;
    if w32(d, t)? != 0x48E7_FFFE || w16(d, t + 4)? != 0x4DFA || w16(d, t + 8)? != 0x51EE || w16(d, t + 12)? != 0x6100 {
        return None;
    }
    Some(())
}

/// The result of the patch walk (sections 1.3 and 2): the patched image, the cost of the player's
/// initialisation without its end constant, and the subsong count.
struct Plan {
    img: Vec<u8>,
    cost: u64,
    subs: u16,
}

/// Walks the module as the player does, applying its patches to a copy. `hook_reg` and
/// `hook_end` are the guest addresses of the two host hooks.
fn plan(d: &[u8], hook_reg: u32, hook_end: u32) -> Option<Plan> {
    check(d)?;
    let mut m = d.to_vec();
    let mut c = C_INIT_FIXED;
    // 2.1: the first 0x40C2, then no-operations up to the next 0x41FA
    let mut p = 0usize;
    let mut n = 0u64;
    loop {
        n += 1;
        if w16(&m, p)? == 0x40C2 {
            break;
        }
        p += 2;
    }
    c += 21 * n + 8;
    n = 0;
    loop {
        n += 1;
        put16(&mut m, p, 0x4E71)?;
        p += 2;
        if w16(&m, p)? == 0x41FA {
            break;
        }
    }
    c += 29 * n + 24;
    // 1.3: the end
    let p41 = p;
    let disp = w16(&m, p41 + 6)? as i16 as i64;
    let base = p41 as i64 + 6 + disp;
    p = p41 + 8;
    n = 0;
    loop {
        n += 1;
        if w16(&m, p)? == 0x43E9 {
            break;
        }
        p += 2;
    }
    c += 21 * n + 69;
    let end = base + 2 * (w16(&m, p + 2)? as i16 as i64);
    if end < 0 || end as usize > m.len() {
        return None;
    }
    let end = end as usize;
    // 2.2 step 1: the walk to the hardware test, with the song-end sites on the way
    p += 4;
    let mut skip = false;
    let mut sites = 0usize;
    loop {
        let x = w32(&m, p)?;
        if !skip {
            c += 29;
            if x == 0x206C_0032 {
                c += 72;
                sites += 1;
                let at = 8 * sites;
                let disp = at as i64 - (p as i64 + 2);
                if disp < i16::MIN as i64 || disp > i16::MAX as i64 {
                    return None;
                }
                // a jump to the hook at module offset 8k (lost if it does not fit), a call in place
                put16(&mut m, at, 0x4EF9);
                put32(&mut m, at + 2, hook_end);
                put16(&mut m, p, 0x6100)?;
                put16(&mut m, p + 2, disp as i16 as u16)?;
                p += 4;
                skip = true;
                continue;
            }
        }
        skip = false;
        c += 29;
        if x == 0x0838_0007 {
            break;
        }
        c += 29;
        if x == 0x0839_0007 {
            break;
        }
        c += 17;
        p += 2;
    }
    c += 16;
    // 2.2 steps 2 and 3: a branch always eight bytes before, the register site
    *m.get_mut(p.checked_sub(8)?)? = 0x60;
    let mut q = p;
    n = 0;
    loop {
        n += 1;
        if w16(&m, q)? == 0x40C1 {
            break;
        }
        q += 2;
    }
    c += 21 * n + 36;
    put16(&mut m, q, 0x4EB9)?;
    put32(&mut m, q + 2, hook_reg)?;
    // step 4: no-operations up to the next 0x4CDF
    let mut r = q + 6;
    n = 0;
    loop {
        n += 1;
        put16(&mut m, r, 0x4E71)?;
        r += 2;
        if w16(&m, r)? == 0x4CDF {
            break;
        }
    }
    c += 29 * n + 4;
    // 1.3: the subsong marker and the count of words 0x0046 up to the end
    loop {
        if r >= end {
            return None;
        }
        c += 23;
        if w32(&m, r)? == 0x56 {
            break;
        }
        c += 18;
        r += 2;
    }
    c += 8;
    let mut n46 = 0usize;
    while r < end {
        c += 32;
        if w16(&m, r)? == 0x46 {
            c += 8;
            n46 += 1;
        }
        r += 2;
    }
    Some(Plan { img: m, cost: c, subs: (n46 / 4).min(0xFFFF) as u16 })
}

/// The noise generator of section 8: `n` bytes from the state `x`.
fn noise(mut x: u32, n: usize) -> Vec<u8> {
    let mut out = Vec::with_capacity(n);
    for _ in 0..n {
        let s = x.wrapping_add(0xE90);
        let s2 = (s & 0xFFFF_0000) | ((s & 0xFFFF) << 4 & 0xFFFF);
        let y = (s2.wrapping_add(x.wrapping_mul(3677)) & 0x7FFF_FFFF).wrapping_sub(1);
        out.push((y >> 8) as u8);
        x = y;
    }
    out
}

/// The mode of a configuration file's bytes (section 3.2).
fn cfg_mode(b: &[u8]) -> u8 {
    if b.len() >= 4 && b[0] == b'W' && b[1] == b'T' && b[2] == 0 && b[3] <= 1 {
        b[3]
    } else {
        0
    }
}

fn read_cfg() -> u8 {
    let path = std::env::var_os("QUARTETPSG_CFG").map(std::path::PathBuf::from).or_else(|| {
        std::env::var_os("HOME").map(|h| std::path::Path::new(&h).join(".config/amigaplayer-rs/EP-Quartet_PSG.cfg"))
    });
    path.and_then(|p| std::fs::read(p).ok()).map_or(0, |b| cfg_mode(&b))
}

fn new(d: &[u8], base: u32, m: &mut Machine) -> Option<Box<dyn Replayer>> {
    build(d, base, m, read_cfg())
}

#[derive(Clone, Copy, PartialEq, Eq)]
enum Wave {
    Noise,
    Pulse,
    Empty,
}

#[derive(Clone, Copy)]
struct Voice {
    vol: u16,
    per: u16,
    status: u8,
}

pub struct QuartetPsg {
    mode: u8,
    base: u32,
    stack: u32,
    hook_reg: u32,
    hook_end: u32,
    /// The buffer block (section 8).
    block: u32,
    subs: u16,
    cur: u16,
    songend: bool,
    resume: Option<u64>,
    /// The driver failed to return: it is not called again.
    dead: bool,
    /// The YM registers R0..R10 as captured.
    ym: [u8; 11],
    /// Mode 0: converter voices A, B, C, N, the noise accumulator count and volume.
    v: [Voice; 4],
    count: u32,
    acc: u32,
    /// The song-end flags (section 4.2).
    flags: [bool; 3],
    cpu: CpuCore,
    // the call in progress: the clock at count 0 and the cycle count
    s: u64,
    cnt: u64,
}

fn build(d: &[u8], base: u32, m: &mut Machine, mode: u8) -> Option<Box<dyn Replayer>> {
    check(d)?;
    let stack = m.alloc(0x1000);
    let hooks = m.alloc(16);
    let block = m.alloc(BLOCK);
    if stack == 0 || hooks == 0 || block == 0 {
        return None;
    }
    let (hook_reg, hook_end) = (hooks, hooks + 8);
    let pl = plan(d, hook_reg, hook_end)?;
    m.bus.write_bytes(base, &pl.img);
    // the buffers (section 8)
    m.bus.write_bytes(block + NOISE1, &noise(0x4849_5050, 1024));
    m.bus.write_bytes(block + NOISE2, &noise(0, 16384));
    m.bus.write_bytes(block + PULSE2, &[0x70, 0x90]);
    m.bus.write_bytes(block + PULSE, &[0xB2, 0x4D]);
    m.bus.write_bytes(block + EMPTY, &[0, 0]);
    let mut cpu = CpuCore::new();
    cpu.set_cpu_type(CpuType::M68000);
    let mut r = QuartetPsg {
        mode,
        base,
        stack,
        hook_reg,
        hook_end,
        block,
        subs: pl.subs,
        cur: 0,
        songend: false,
        resume: None,
        dead: false,
        ym: [0; 11],
        v: [Voice { vol: 0, per: 0x100, status: 0 }; 4],
        count: 0,
        acc: 0,
        flags: [true; 3],
        cpu,
        s: 0,
        cnt: 0,
    };
    // 3.1: the start-up, counted from the run's origin
    let origin = m.bus.clock.saturating_sub(S0);
    let c_pre = if mode == 1 { 1345 } else { 1269 };
    let c_end = if mode == 1 { 161 + 44 } else { 161 };
    let i = origin + S0 + (c_pre + pl.cost + c_end) / 2;
    m.bus.clock = m.bus.clock.max(i);
    r.begin(&mut m.bus, i, 0);
    r.init_sound(&mut m.bus, 0);
    m.bus.clock = m.bus.clock.max(r.now());
    Some(Box::new(r))
}

impl QuartetPsg {
    fn adv(&mut self, bus: &mut Bus, cycles: u64) {
        self.cnt += cycles;
        m68k_rc::Bus::cycles(bus, self.cnt);
    }

    /// The clock at the current count.
    fn now(&self) -> u64 {
        self.s + self.cnt / 2
    }

    /// Starts a call: the clock `start` at count 0, `pre` cycles already spent.
    fn begin(&mut self, bus: &mut Bus, start: u64, pre: u64) {
        self.s = start;
        self.cnt = pre;
        bus.clock = bus.clock.max(start);
        bus.epoch = (start, 0);
    }

    fn wr(&mut self, bus: &mut Bus, reg: u32, v: u16) {
        bus.write_word(0xDF_F000 + reg, v);
    }

    fn rd(&mut self, bus: &mut Bus, reg: u32) -> u16 {
        AddressBus::read_word(bus, 0xDF_F000 + reg)
    }

    /// The Paula volume of a converter volume (section 7, with the factor 64 of the host's
    /// defaults).
    fn scale(v: u32) -> u16 {
        ((v * 64) >> 6) as u16
    }

    fn call(&mut self, bus: &mut Bus, entry: u32, d0: u32) {
        if let Err(e) = self.run(bus, entry, d0) {
            log::error!("{e}");
            self.songend = true;
            self.dead = true;
        }
    }

    /// Runs the driver's entry at `entry` until it returns, with `d0` and A0 = module address.
    fn run(&mut self, bus: &mut Bus, entry: u32, d0: u32) -> Result<(), String> {
        let ret = (self.stack + 0x800) & !3;
        let sp = ret - 4;
        bus.w32(sp, ret);
        self.cpu.dar = [0; 16];
        self.cpu.dar[0] = d0;
        self.cpu.dar[8] = self.base;
        self.cpu.dar[15] = sp;
        self.cpu.set_sr(0x2000);
        self.cpu.pc = entry;
        self.cpu.invalidate_prefetch();
        let mut executed = 0u64;
        loop {
            let pc = self.cpu.pc;
            if pc == ret && self.cpu.dar[15] == ret {
                return Ok(());
            }
            executed += 1;
            if executed > 5_000_000 {
                return Err(format!("quartetpsg: driver did not return (PC=${pc:06x})"));
            }
            if pc == self.hook_reg {
                self.reg_hook(bus);
                continue;
            }
            if pc == self.hook_end {
                self.end_hook(bus);
                continue;
            }
            let ins = m68k_rc::decode::decode_model(pc, &mut |a| bus.r16(a), m68k_rc::Model::M68000);
            self.cnt += m68k_rc::cycles::cycles(&ins) as u64;
            m68k_rc::Bus::cycles(bus, self.cnt);
            match self.cpu.step(bus) {
                StepResult::Ok { .. } => {}
                other => return Err(format!("quartetpsg: {other:?} at PC=${:06x}", self.cpu.ppc)),
            }
        }
    }

    /// Returns from a hook as its last instruction does.
    fn hook_return(&mut self, bus: &mut Bus) {
        let sp = self.cpu.dar[15];
        self.cpu.pc = bus.r32(sp);
        self.cpu.dar[15] = sp.wrapping_add(4);
        self.cpu.invalidate_prefetch();
    }

    /// The register hook (section 4.1): 11 bytes at A5 into the YM shadow, A5 advances.
    fn reg_hook(&mut self, bus: &mut Bus) {
        self.adv(bus, 200);
        let a5 = self.cpu.dar[13];
        let mut b = [0u8; 11];
        for (i, x) in b.iter_mut().enumerate() {
            *x = bus.r8(a5.wrapping_add(i as u32));
        }
        // the order of the buffer: R1, R0, R3, R2, R5, R4, R6, R7, R8, R9, R10
        for (i, r) in [1usize, 0, 3, 2, 5, 4, 6, 7, 8, 9, 10].into_iter().enumerate() {
            self.ym[r] = b[i];
        }
        self.cpu.dar[13] = a5.wrapping_add(11);
        self.hook_return(bus);
    }

    /// The song-end hook (section 4.2).
    fn end_hook(&mut self, bus: &mut Bus) {
        let a4 = self.cpu.dar[12];
        self.cpu.dar[8] = bus.r32(a4.wrapping_add(0x32));
        let c = bus.r8(a4.wrapping_add(0x3E));
        self.adv(bus, 48 + 25);
        if c == 8 {
            self.flags[0] = false;
            self.adv(bus, 22);
        } else {
            self.adv(bus, 25);
            if c == 10 {
                self.flags[1] = false;
                self.adv(bus, 26);
            } else {
                self.adv(bus, 25);
                if c == 9 {
                    self.flags[2] = false;
                    self.adv(bus, 16);
                }
            }
        }
        self.adv(bus, 21);
        if self.flags.iter().all(|f| !f) {
            self.adv(bus, 84);
            self.songend = true;
            self.flags = [true; 3];
        }
        self.adv(bus, 44);
        self.hook_return(bus);
    }

    // ---- mode 0 -------------------------------------------------------------------------

    fn line(&self) -> u64 {
        (self.now() / 227 % 313) & 0xFF
    }

    /// The raster wait of section 5.5 (bounded: the line changes within 454 cycles).
    fn line_sync(&mut self, bus: &mut Bus) {
        self.adv(bus, 12);
        let r0 = self.line();
        for _ in 0..1000 {
            self.adv(bus, 12);
            let l = self.line();
            self.adv(bus, 9);
            if l != r0 {
                break;
            }
        }
        for _ in 0..1000 {
            self.adv(bus, 16);
            let h = self.now() % 227;
            self.adv(bus, 9);
            if h >= 22 {
                break;
            }
        }
    }

    /// Polls INTREQR until all bits of `mask` are set (bounded).
    fn wait_irq(&mut self, bus: &mut Bus, mask: u16) {
        for _ in 0..200_000 {
            self.adv(bus, 12);
            let r = self.rd(bus, 0x01E);
            self.adv(bus, 17);
            if r & mask == mask {
                break;
            }
        }
    }

    fn wave(&self, w: Wave) -> (u32, u16) {
        match w {
            Wave::Noise => (self.block + NOISE1, 0x200),
            Wave::Pulse => (self.block + PULSE, 1),
            Wave::Empty => (self.block + EMPTY, 1),
        }
    }

    /// The restart sequence of section 5.3 for Paula voice `pv`, with the voice's period `per`.
    fn restart(&mut self, bus: &mut Bus, pv: usize, w: Wave, per: u16) {
        let r = 16 * pv as u32;
        let b = 1u16 << pv;
        let (addr, len) = self.wave(w);
        self.adv(bus, 30);
        self.line_sync(bus);
        self.adv(bus, 16);
        self.wr(bus, 0xA6 + r, 1);
        self.adv(bus, 12);
        let a = self.rd(bus, 0x002) & b;
        self.adv(bus, 28 + 12);
        self.wr(bus, 0x09C, a << 7);
        self.adv(bus, 12);
        self.wr(bus, 0x096, a);
        // one poll even when nothing is waited for (the mask is 0)
        self.wait_irq(bus, a << 7);
        self.adv(bus, 12);
        self.wr(bus, 0xA0 + r, (addr >> 16) as u16);
        self.wr(bus, 0xA2 + r, addr as u16);
        self.adv(bus, 12);
        self.wr(bus, 0xA4 + r, len);
        self.adv(bus, 18 + SL[pv] + 4 + 20);
        self.wr(bus, 0xA6 + r, per);
        self.line_sync(bus);
        self.adv(bus, 12);
        let o = if self.rd(bus, 0x002) & b == 0 { b } else { 0 };
        self.adv(bus, 40 + 12);
        self.wr(bus, 0x09C, o << 7);
        self.adv(bus, 12);
        self.wr(bus, 0x096, 0x8000 | o);
        self.wait_irq(bus, o << 7);
        self.line_sync(bus);
        self.adv(bus, 12);
        self.wr(bus, 0xA0 + r, (addr >> 16) as u16);
        self.wr(bus, 0xA2 + r, addr as u16);
        self.adv(bus, 12);
        self.wr(bus, 0xA4 + r, len);
        self.adv(bus, 16);
    }

    /// The write step of section 5.4 for converter voice `i`.
    fn write_step(&mut self, bus: &mut Bus, i: usize) {
        let pv = PV[i];
        let r = 16 * pv as u32;
        self.adv(bus, 56 + CV[pv] + SV[pv]);
        let vol = Self::scale(self.v[i].vol as u32);
        self.wr(bus, 0xA8 + r, vol);
        self.adv(bus, 24);
        let per = self.v[i].per;
        self.wr(bus, 0xA6 + r, per);
        self.adv(bus, 10 + SV[pv]);
    }

    /// Voice `i` silent: volume 0, period 0x100, status 0, restarted with the empty waveform.
    fn silence(&mut self, bus: &mut Bus, i: usize) {
        self.v[i] = Voice { vol: 0, per: 0x100, status: 0 };
        self.restart(bus, PV[i], Wave::Empty, 0x100);
    }

    /// The noise handling of voice `i`: period from R6, restart with the noise waveform if its
    /// status is not 2.
    fn noise_voice(&mut self, bus: &mut Bus, i: usize) {
        self.v[i].per = (self.ym[6] as u16 & 31) * 16 + 142;
        self.adv(bus, 50 + 25);
        if self.v[i].status != 2 {
            self.v[i].status = 2;
            self.adv(bus, 62);
            let per = self.v[i].per;
            self.restart(bus, PV[i], Wave::Noise, per);
            self.adv(bus, 10);
        }
    }

    fn convert0(&mut self, bus: &mut Bus) {
        self.adv(bus, 110);
        for i in 0..3 {
            if i > 0 {
                self.adv(bus, 82);
            }
            self.adv(bus, 37);
            let p = ((self.ym[2 * i + 1] as u32) << 8 | self.ym[2 * i] as u32) & 0xFFF;
            let l = (self.ym[8 + i] & 15) as usize;
            let tone = self.ym[7] & (1 << i) == 0;
            let noise = self.ym[7] & (8 << i) == 0;
            self.v[i].vol = VT0[l];
            if tone {
                self.v[i].per = (((p * 14540) >> 10) + 1) as u16;
                self.adv(bus, 102 + 15 + 25);
                if noise {
                    self.adv(bus, 40);
                    self.count += 1;
                    self.acc += self.v[i].vol as u32;
                }
                if self.v[i].status != 1 {
                    self.v[i].status = 1;
                    self.adv(bus, 62);
                    let per = self.v[i].per;
                    self.restart(bus, PV[i], Wave::Pulse, per);
                    self.adv(bus, 10);
                }
            } else if noise {
                self.adv(bus, 15);
                self.noise_voice(bus, i);
            } else {
                self.adv(bus, 15 + 82);
                self.silence(bus, i);
            }
            self.write_step(bus, i);
        }
        self.adv(bus, 37);
        if self.count == 0 {
            self.adv(bus, 21);
            if self.v[3].status != 0 {
                self.adv(bus, 82);
                self.silence(bus, 3);
                self.write_step(bus, 3);
            } else {
                self.adv(bus, 16);
            }
        } else {
            self.adv(bus, 13);
            let acc = self.acc;
            self.v[3].vol = acc.min(0xFFFF) as u16;
            if self.count >= 2 {
                self.adv(bus, 13);
            }
            if self.count == 2 {
                self.adv(bus, 12);
                self.v[3].vol = (acc / 2).min(0xFFFF) as u16;
            }
            if self.count == 3 {
                self.adv(bus, 158);
                self.v[3].vol = (acc / 3).min(0xFFFF) as u16;
            }
            self.adv(bus, 18);
            self.noise_voice(bus, 3);
            self.write_step(bus, 3);
            self.adv(bus, 42);
            self.count = 0;
            self.acc = 0;
        }
    }

    // ---- mode 1 -------------------------------------------------------------------------

    fn convert1(&mut self, bus: &mut Bus) {
        self.adv(bus, 56);
        let mut sum = 0u32;
        let mut bits = 0u16;
        for i in 0..3 {
            let r = 16 * i as u32;
            let p = ((self.ym[2 * i + 1] as u32) << 8 | self.ym[2 * i] as u32) & 0xFFF;
            let l = (self.ym[8 + i] & 15) as usize;
            let noise = self.ym[7] & (8 << i) == 0;
            let mut per = p * 1419 / 100;
            if per < 123 {
                per = 0;
            }
            let (mut t, mut n) = (l, 0usize);
            self.adv(bus, 133);
            if p != 0 {
                self.adv(bus, 190);
            }
            self.adv(bus, 19);
            if noise {
                n = l;
                self.adv(bus, 13);
                if l != 0 {
                    self.adv(bus, 13);
                    if p != 0 {
                        self.adv(bus, 13 + if l < 2 { 4 } else { 0 });
                        self.adv(bus, 13 + if l == 1 { 4 } else { 0 });
                        t = if l >= 2 { l - 2 } else { 1 };
                        n = if l >= 2 { l - 1 } else { 1 };
                    }
                }
            }
            sum += VT1[n] as u32;
            self.adv(bus, 17 + if per == 0 { 4 } else { 0 });
            self.adv(bus, 52);
            self.adv(bus, 17);
            if per != 0 {
                bits |= 1 << i;
                self.adv(bus, 12);
                self.wr(bus, 0xA6 + r, per as u16);
                self.adv(bus, 18 + SV[i] + 12);
            }
            self.adv(bus, 4 + 18 + CV[i] + 18 + SV[i] + 12);
            self.wr(bus, 0xA8 + r, Self::scale(VT1[t] as u32));
            self.adv(bus, 26);
        }
        self.adv(bus, 46 + 12);
        self.wr(bus, 0xD6, 0x80 + 0x20 * (self.ym[6] as u16 & 31));
        self.adv(bus, 18 + 149 + 17 + if sum >= 64 { 4 } else { 0 });
        self.adv(bus, 4 + 18 + 214 + 18 + 149 + 12);
        self.wr(bus, 0xD8, Self::scale(sum.min(64)));
        let nbit = if self.ym[7] & 0x38 != 0x38 { 8u16 } else { 0 };
        let on = bits | nbit;
        self.adv(bus, 49 + 16);
        self.wr(bus, 0x096, 0x8000 | on);
        self.adv(bus, 8 + 16);
        self.wr(bus, 0x096, 0x000F & !on);
        self.adv(bus, 16);
    }

    // ---- calls --------------------------------------------------------------------------

    /// InitSound (section 3.3) for subsong `sub`, from the current count.
    fn init_sound(&mut self, bus: &mut Bus, sub: u16) {
        self.flags = [true; 3];
        self.songend = false;
        self.ym = [0; 11];
        if self.mode == 1 {
            self.ym[7] = 0xFF;
            self.adv(bus, 1379);
            self.wr(bus, 0x096, 0x000F);
            self.adv(bus, 24);
            for v in 0..4u32 {
                let (addr, len) = if v < 3 { (self.block + PULSE2, 1) } else { (self.block + NOISE2, 0x2000) };
                let r = 16 * v;
                self.wr(bus, 0xA0 + r, (addr >> 16) as u16);
                self.wr(bus, 0xA2 + r, addr as u16);
                self.adv(bus, 8);
                self.wr(bus, 0xA4 + r, len);
                self.adv(bus, 8);
                self.wr(bus, 0xA6 + r, 1);
                self.adv(bus, 12);
                self.wr(bus, 0xA8 + r, 0);
                self.wr(bus, 0xAA + r, 0);
                if v < 3 {
                    self.adv(bus, 20);
                }
            }
            self.adv(bus, 200 + 64);
        } else {
            self.ym[7] = 0x3F;
            self.v = [Voice { vol: 0, per: 0x100, status: 0 }; 4];
            self.count = 0;
            self.acc = 0;
            self.adv(bus, 1583);
        }
        let base = self.base;
        self.call(bus, base, sub as u32);
    }
}

impl Replayer for QuartetPsg {
    fn format(&self) -> &'static str {
        "Quartet PSG"
    }

    fn title(&self) -> String {
        String::new()
    }

    fn songend(&self) -> bool {
        self.songend
    }

    fn subsongs(&self) -> (u16, u16, u16) {
        (0, self.subs.max(1) - 1, self.cur)
    }

    fn set_subsong(&mut self, n: u16, hw: &mut Hw) {
        if n >= self.subs.max(1) {
            return;
        }
        self.cur = n;
        self.dead = false;
        let bus = &mut *hw.bus;
        // EndSound (section 3.4), a pause of the two volume calls, InitSound
        let t = bus.clock;
        self.begin(bus, t, 0);
        self.adv(bus, 28);
        self.wr(bus, 0x096, 0x000F);
        for (i, c) in [16u64, 12, 12, 12].into_iter().enumerate() {
            self.adv(bus, c);
            self.wr(bus, 0xA8 + 16 * i as u32, 0);
        }
        self.adv(bus, 16);
        let t = self.now() + 236;
        bus.clock = bus.clock.max(t);
        self.begin(bus, t, 0);
        self.init_sound(bus, n);
        bus.clock = bus.clock.max(self.now());
        self.resume = Some(self.now() + TICK);
    }

    fn subsong_tick_at(&mut self) -> Option<u64> {
        self.resume.take()
    }

    fn tick(&mut self, hw: &mut Hw) {
        if self.dead {
            return;
        }
        let bus = &mut *hw.bus;
        let start = bus.clock;
        self.begin(bus, start, 266);
        let entry = self.base + 4;
        self.call(bus, entry, 0);
        if !self.dead {
            self.adv(bus, 39);
            if self.mode == 1 {
                self.convert1(bus);
                self.adv(bus, 172);
            } else {
                self.convert0(bus);
                self.adv(bus, 182);
            }
        }
        bus.clock = bus.clock.max(self.now());
    }
}

