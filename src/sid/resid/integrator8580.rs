use super::filter_model_config::Dither;
use super::filter_model_config8580::FilterModelConfig8580;

// 8580 integrator
//
//                   +---C---+
//                   |       |
//     vi -----Rfc---o--[A>--o-- vo
//                   vx
//
//     IRfc + ICr = 0
//     IRfc + C*(vc - vc0)/dt = 0
//     dt/C*(IRfc) + vc - vc0 = 0
//     vc = vc0 - n*(IRfc(vi,vx))
//     vc = vc0 - n*(IRfc(vi,g(vc)))
//
// IRfc = K*W/L*(Vgst^2 - Vgdt^2) = n*((Vddt - vx)^2 - (Vddt - vi)^2)
//
// Rfc gate voltage is generated by an OP Amp and depends on chip temperature.

pub struct Integrator8580 {
    pub vx: i32,
    pub vc: i32,

    n_vgt: u16,
    n_dac: u16,
}

impl Integrator8580 {
    pub fn new(fmc: &FilterModelConfig8580, dither: &mut Dither) -> Self {
        let mut this = Integrator8580 {
            vx: 0,
            vc: 0,
            n_vgt: 0,
            n_dac: 0,
        };

        this.set_v(fmc, 1.5, dither);

        this
    }

    /// Set filter cutoff resistor ratio
    pub fn set_fc(&mut self, fmc: &FilterModelConfig8580, wl: f64) {
        // Normalized current factor, 1 cycle at 1Mhz
        self.n_dac = fmc.get_normalized_current_factor(17, wl);
    }

    /// Set FC gate voltage multiplier
    pub fn set_v(&mut self, fmc: &FilterModelConfig8580, v: f64, dither: &mut Dither) {
        // Gate voltage is controlled by the switched capacitor voltage divider
        // Ua = Ue * v = 4.75v  1<v<2
        let vg = fmc.get_v_ref() * v;
        let vgt = vg - fmc.base.vth;

        // Vg - Vth, normalized so that translated values can be subtracted:
        // Vgt - x = (Vgt - t) - (x - t)
        self.n_vgt = fmc.base.get_normalized_value(vgt, dither);
    }

    pub fn restart(&mut self) {
        self.vx = 16384;
        self.vc = 16384;
    }

    #[inline(always)]
    pub fn solve(&mut self, vi: i32, fmc: &FilterModelConfig8580) -> i32 {
        let n_vgt = i32::from(self.n_vgt);

        // DAC voltages
        let vgst = n_vgt.wrapping_sub(self.vx) as u32;
        let vgdt = (if vi < n_vgt { n_vgt.wrapping_sub(vi) } else { 0 }) as u32; // triode/saturation mode

        let vgst_2 = vgst.wrapping_mul(vgst);
        let vgdt_2 = vgdt.wrapping_mul(vgdt);

        // DAC current, scaled by (1/m)*2^13*m*2^16*m*2^16*2^-15 = m*2^30
        let n_i_dac = i32::from(self.n_dac).wrapping_mul((vgst_2.wrapping_sub(vgdt_2) as i32) >> 15) >> 4;

        // Change in capacitor charge
        self.vc = self.vc.wrapping_add(n_i_dac);

        // vx = g(vc)
        let tmp = (self.vc >> 15) - i32::from(i16::MIN);
        self.vx = i32::from(fmc.base.get_opamp_rev(tmp));

        // Return vo
        self.vx - (self.vc >> 14)
    }
}
