use std::f64::consts::PI;

use super::fmath;

// Abstraction of a resampling process. Given enough input, produces output.
// The C# abstract class is the `Resampler` enum here.

/// Maximum error acceptable in I0 is 1e-6, or ~96 dB
const I0E: f64 = 1e-6;

/// Size of the ring buffer, must be a power of 2
const RING_SIZE: usize = 2048;

const BITS: i32 = 16;

/// Largest FIR table accepted (entries), upstream has no limit
const MAX_FIR_ENTRIES: usize = 1 << 23;

const THRESHOLD: i32 = 28000;

// Limiter

#[inline(always)]
fn clipper(x: i32, m: i32) -> i32 {
    if x < THRESHOLD {
        return x;
    }

    let max_val = f64::from(m);
    let t = f64::from(THRESHOLD) / max_val;
    let a = 1.0 - t;
    let b = 1.0 / a;

    let mut value = f64::from(x - THRESHOLD) / max_val;
    value = a * fmath::tanh(b * value);

    (f64::from(THRESHOLD) + (value * max_val)) as i32
}

/// Soft clipping implementation
#[inline(always)]
fn soft_clip_impl(x: i32) -> i32 {
    if x < 0 {
        clipper(x.wrapping_neg(), 32768).wrapping_neg()
    } else {
        clipper(x, 32767)
    }
}

/// Soft Clipping into 16 bit range [-32768,32767]
#[inline(always)]
pub fn soft_clip(x: i32) -> i16 {
    soft_clip_impl(x) as i16
}

/// The sample rates must be usable by the filters: finite, positive and the
/// output rate not above the input rate
fn check_rates(clock_frequency: f64, sampling_frequency: f64) -> Result<(), &'static str> {
    if !(clock_frequency.is_finite() && sampling_frequency.is_finite()) {
        return Err("Unsupported sampling frequency");
    }

    if clock_frequency <= 0.0 || sampling_frequency <= 0.0 || clock_frequency < sampling_frequency {
        return Err("Unsupported sampling frequency");
    }

    Ok(())
}

/// Return sample with linear interpolation
pub struct ZeroOrderResampler {
    /// Last sample
    cached_sample: i32,

    /// Number of cycles per sample
    cycles_per_sample: i32,

    sample_offset: i32,

    /// Calculated sample
    output_value: i32,
}

impl ZeroOrderResampler {
    pub fn new(clock_frequency: f64, sampling_frequency: f64) -> Result<Self, &'static str> {
        check_rates(clock_frequency, sampling_frequency)?;

        Ok(ZeroOrderResampler {
            cached_sample: 0,
            cycles_per_sample: (clock_frequency / sampling_frequency * 1024.0) as i32,
            sample_offset: 0,
            output_value: 0,
        })
    }

    #[inline(always)]
    pub fn input(&mut self, sample: i32) -> bool {
        let mut ready = false;

        if self.sample_offset < 1024 {
            self.output_value = self
                .cached_sample
                .wrapping_add(self.sample_offset.wrapping_mul(sample.wrapping_sub(self.cached_sample)) >> 10);
            ready = true;
            self.sample_offset += self.cycles_per_sample;
        }

        self.sample_offset -= 1024;

        self.cached_sample = sample;

        ready
    }

    #[inline(always)]
    pub fn output(&self) -> i32 {
        self.output_value
    }

    pub fn reset(&mut self) {
        self.sample_offset = 0;
        self.cached_sample = 0;
    }
}

/// This is the theoretically correct (and computationally intensive) audio sample generation.
/// The samples are generated by resampling to the specified sampling frequency.
/// The work rate is inversely proportional to the percentage of the bandwidth
/// allocated to the filter transition band.
///
/// This implementation is based on the paper "A Flexible Sampling-Rate Conversion Method",
/// by J. O. Smith and P. Gosset, or rather on the expanded tutorial on the
/// [Digital Audio Resampling Home Page](http://www-ccrma.stanford.edu/~jos/resample/).
///
/// By building shifted FIR tables with samples according to the sampling frequency,
/// this implementation dramatically reduces the computational effort in the
/// filter convolutions, without any loss of accuracy.
/// The filter convolutions are also vectorizable on current hardware
pub struct SincResampler {
    /// Table of the fir filter coefficients, `fir_res` rows of `fir_n` entries
    fir_table: Vec<i16>,

    sample_index: usize,

    /// Filter resolution
    fir_res: usize,

    /// Filter length
    fir_n: usize,

    cycles_per_sample: i32,
    sample_offset: i32,
    output_value: i32,
    sample: Vec<i32>,
}

impl SincResampler {
    /// Use a clock freqency of 985248Hz for PAL C64, 1022730Hz for NTSC
    /// C64.
    ///
    /// For resampling, the ratio between the clock frequency and the
    /// sample frequency is limited as follows:
    ///   125*clock_freq/sample_freq < 16384
    ///
    /// E.g. provided a clock frequency of ~ 1MHz, the sample frequency
    /// can not be set lower than ~ 8kHz.
    /// A lower sample frequency would make the resampling code overfill
    /// its 16k sample ring buffer.
    ///
    /// Upstream fails with an exception somewhere later when the ratio is out of
    /// range, here it is an error
    pub fn new(
        clock_frequency: f64,
        sampling_frequency: f64,
        highest_accurate_frequency: f64,
    ) -> Result<Self, &'static str> {
        check_rates(clock_frequency, sampling_frequency)?;

        let cycles_per_sample = (clock_frequency / sampling_frequency * 1024.0) as i32;

        // 16-bits -> -96dB stopband attenuation
        let a = -20.0 * fmath::log10(1.0 / f64::from(1 << BITS));

        // A fraction of the bandwidth is allocated to the transition band, which we double
        // because we design the filter to transition halfway at nyquist
        let dw = (1.0 - 2.0 * highest_accurate_frequency / sampling_frequency) * PI * 2.0;

        if !(dw.is_finite() && dw > 0.0) {
            return Err("Unsupported sampling frequency");
        }

        // For calculation of beta and N see the reference for the kaiserord
        // function in the MATLAB Signal Processing Toolbox:
        // http://www.mathworks.com/help/signal/ref/kaiserord.html
        let beta = 0.1102 * (a - 8.7);
        let i0_beta = i0(beta);
        let cycles_per_sample_d = clock_frequency / sampling_frequency;
        let inv_cycles_per_sample_d = sampling_frequency / clock_frequency;

        // The filter order will maximally be 124 with the current constraints.
        // N >= (96.33 - 7.95)/(2 * pi * 2.285 * (maxfreq - passbandfreq) >= 123
        // The filter order is equal to the number of zero crossings, i.e.
        // it should be an even number (sinc is symmetric with respect to x = 0)
        let mut n = ((a - 7.95) / (2.285 * dw) + 0.5) as i32;
        n += n & 1;

        // The filter length is equal to the filter order + 1.
        // The filter length must be an odd number (sinc is symmetric with respect to
        // x = 0)
        let mut fir_n = (f64::from(n) * cycles_per_sample_d) as i32 + 1;
        fir_n |= 1;

        // Error is bounded by err < 1.234 / L^2, so L = sqrt(1.234 / (2^-16)) = sqrt(1.234 * 2^16)
        let fir_res = ((1.234 * f64::from(1 << BITS)).sqrt() * inv_cycles_per_sample_d).ceil() as i32;

        // firN*firRES represent the total resolution of the sinc sampling. JOS
        // recommends a length of 2^BITS, but we don't quite use that good a filter.
        // The filter test program indicates that the filter performs well, though

        // The ring buffer must hold the filter plus one sample
        if fir_n < 1 || fir_n as usize >= RING_SIZE || fir_res < 1 {
            return Err("Unsupported sampling frequency");
        }

        let fir_n = fir_n as usize;
        let fir_res = fir_res as usize;

        if fir_res.checked_mul(fir_n).is_none_or(|e| e > MAX_FIR_ENTRIES) {
            return Err("Unsupported sampling frequency");
        }

        // Allocate memory for FIR tables
        let mut fir_table = vec![0i16; fir_res * fir_n];

        // The cutoff frequency is midway through the transition band, in effect the same as nyquist
        let wc = PI;

        // Calculate the sinc tables
        let scale = 32768.0 * wc * inv_cycles_per_sample_d / PI;

        // We're not interested in the fractional part
        // so use int division before converting to double
        let tmp = fir_n / 2;
        let fir_n2 = tmp as f64;

        for i in 0..fir_res {
            let j_phase = i as f64 / fir_res as f64 + fir_n2;

            for j in 0..fir_n {
                let x = j as f64 - j_phase;

                let xt = x / fir_n2;
                let kaiser_xt = if xt.abs() < 1.0 {
                    i0(beta * (1.0 - xt * xt).sqrt()) / i0_beta
                } else {
                    0.0
                };

                let wt = wc * x * inv_cycles_per_sample_d;
                let sinc_wt = if wt.abs() >= 1e-8 { fmath::sin(wt) / wt } else { 1.0 };

                fir_table[i * fir_n + j] = (scale * sinc_wt * kaiser_xt) as i16;
            }
        }

        Ok(SincResampler {
            fir_table,
            sample_index: 0,
            fir_res,
            fir_n,
            cycles_per_sample,
            sample_offset: 0,
            output_value: 0,
            sample: vec![0; RING_SIZE * 2],
        })
    }

    #[inline(always)]
    pub fn input(&mut self, input: i32) -> bool {
        let mut ready = false;

        self.sample[self.sample_index] = input;
        self.sample[self.sample_index + RING_SIZE] = input;
        self.sample_index = (self.sample_index + 1) & (RING_SIZE - 1);

        if self.sample_offset < 1024 {
            self.output_value = self.fir(self.sample_offset);
            ready = true;
            self.sample_offset += self.cycles_per_sample;
        }

        self.sample_offset -= 1024;

        ready
    }

    #[inline(always)]
    pub fn output(&self) -> i32 {
        self.output_value
    }

    pub fn reset(&mut self) {
        self.sample.fill(0);
        self.sample_offset = 0;
    }

    #[inline(always)]
    fn fir(&self, sub_cycle: i32) -> i32 {
        // sub_cycle is in [0, 1024) (the constructor makes the offset never
        // negative) so the table index is below fir_res
        let sub_cycle = sub_cycle.clamp(0, 1023) as usize;

        // Find the first of the nearest fir tables close to the phase
        let mut fir_table_first = (sub_cycle * self.fir_res) >> 10;
        let fir_table_offset = ((sub_cycle * self.fir_res) & 0x3ff) as i32;

        // Find firN most recent samples, plus one extra in case the FIR wraps
        let mut sample_start = self.sample_index + RING_SIZE - self.fir_n - 1;

        let v1 = self.convolve(sample_start, fir_table_first);

        // Use next FIR table, wrap around to first FIR table using
        // previous sample
        fir_table_first += 1;
        if fir_table_first == self.fir_res {
            fir_table_first = 0;
            sample_start += 1;
        }

        let v2 = self.convolve(sample_start, fir_table_first);

        // Linear interpolation between the sinc tables yields good
        // approximation for the exact value
        v1.wrapping_add(fir_table_offset.wrapping_mul(v2.wrapping_sub(v1)) >> 10)
    }

    /// Calculate convolution with sample and sinc
    #[inline(always)]
    fn convolve(&self, a: usize, row: usize) -> i32 {
        let b = &self.fir_table[row * self.fir_n..(row + 1) * self.fir_n];
        let s = &self.sample[a..a + self.fir_n];

        let out = s
            .iter()
            .zip(b)
            .fold(0i32, |acc, (&s, &b)| acc.wrapping_add(s.wrapping_mul(i32::from(b))));

        out.wrapping_add(1 << 14) >> 15
    }
}

/// Compute the 0th order modified Bessel function of the first kind.
/// This function is originally from resample-1.5/filterkit.c by
/// J. O. Smith. It is used to build the Kaiser window for resampling
fn i0(x: f64) -> f64 {
    let mut sum = 1.0;
    let mut u = 1.0;
    let mut n = 1.0;
    let half_x = x / 2.0;

    loop {
        let temp = half_x / n;
        u *= temp * temp;
        sum += u;
        n += 1.0;

        if u < I0E * sum {
            break;
        }
    }

    sum
}

/// Compose a more efficient SINC from chaining two other SINCs
pub struct TwoPassSincResampler {
    s1: SincResampler,
    s2: SincResampler,
}

impl TwoPassSincResampler {
    /// Named constructor
    pub fn create(clock_frequency: f64, sampling_frequency: f64) -> Result<Self, &'static str> {
        check_rates(clock_frequency, sampling_frequency)?;

        // Set the passband frequency slightly below half sampling frequency
        //   pass_freq <= 0.9*sample_freq/2
        //
        // This constraint ensures that the FIR table is not overfilled.
        // For higher sampling frequencies we're fine with 20KHz
        let half_freq = if sampling_frequency > 44000.0 {
            20000.0
        } else {
            sampling_frequency * 0.45
        };

        // Calculation according to Laurent Ganier.
        // It evaluates to about 120 kHz at typical settings.
        // Some testing around the chosen value seems to confirm that this does work
        let intermediate_frequency = 2.0 * half_freq
            + (2.0 * half_freq * clock_frequency * (sampling_frequency - 2.0 * half_freq) / sampling_frequency).sqrt();

        let s1 = SincResampler::new(clock_frequency, intermediate_frequency, half_freq)?;
        let s2 = SincResampler::new(intermediate_frequency, sampling_frequency, half_freq)?;

        Ok(TwoPassSincResampler { s1, s2 })
    }

    #[inline(always)]
    pub fn input(&mut self, sample: i32) -> bool {
        self.s1.input(sample) && self.s2.input(self.s1.output())
    }

    #[inline(always)]
    pub fn output(&self) -> i32 {
        self.s2.output()
    }

    pub fn reset(&mut self) {
        self.s1.reset();
        self.s2.reset();
    }
}

/// The resampler of a `Sid`
pub enum Resampler {
    ZeroOrder(ZeroOrderResampler),
    TwoPassSinc(Box<TwoPassSincResampler>),
}

impl Resampler {
    /// Input a sample into resampler. Output "true" when resampler is
    /// ready with new sample
    #[inline(always)]
    pub fn input(&mut self, sample: i32) -> bool {
        match self {
            Resampler::ZeroOrder(r) => r.input(sample),
            Resampler::TwoPassSinc(r) => r.input(sample),
        }
    }

    pub fn reset(&mut self) {
        match self {
            Resampler::ZeroOrder(r) => r.reset(),
            Resampler::TwoPassSinc(r) => r.reset(),
        }
    }

    #[inline(always)]
    pub fn output(&self) -> i32 {
        match self {
            Resampler::ZeroOrder(r) => r.output(),
            Resampler::TwoPassSinc(r) => r.output(),
        }
    }

    /// Output a sample from resampler
    #[inline(always)]
    pub fn get_output(&self, scale_factor: i32) -> i16 {
        let out = scale_factor.wrapping_mul(self.output()) / 2;
        soft_clip(out)
    }
}
