/// `FREQ_PARAM_MULT`: `128.0f / (24.0f * 256.0f)`.
#[cfg(test)]
const FREQ_PARAM_MULT: f32 = 128.0 / (24.0 * 256.0);

/// `libxmp_filter_setup`: the coefficients `(a0, b0, b1)` of the filter at
/// output rate `srate` for an IT-style `cutoff` and `res` (0-255 each;
/// cutoff 0-255 maps to about 100 Hz-8000 Hz).
#[allow(clippy::approx_constant, clippy::excessive_precision)]
pub fn filter_setup(srate: i32, cutoff: i32, res: i32) -> (i32, i32, i32) {
    let fs = srate as f32;
    let cutoff = cutoff.clamp(0, 255);
    let res = res.clamp(0, 255);

    // powf(2.0f, cutoff * FREQ_PARAM_MULT + 0.25f), from a table: libm powfs may
    // round differently (the wasm build's is not glibc's), the table is glibc's
    let mut fc = 110.0f32 * f32::from_bits(POW2_TABLE[cutoff as usize]);
    if fc > fs / 2.0 {
        fc = fs / 2.0;
    }

    // r = fs / (2.0 * 3.14159265358979f * fc): a double expression, stored in a float
    let r = (fs as f64 / (2.0 * (3.14159265358979f32 as f64) * fc as f64)) as f32;
    let d = (RESONANCE_TABLE[(res >> 1) as usize] as f64 * (r as f64 + 1.0) - 1.0) as f32;
    let e = r * r;

    let fg = (1.0 / (1.0 + d as f64 + e as f64)) as f32;
    let fb0 = ((d + e + e) as f64 / (1.0 + d as f64 + e as f64)) as f32;
    let fb1 = (-e as f64 / (1.0 + d as f64 + e as f64)) as f32;

    let scale = (1i32 << FILTER_SHIFT) as f32;
    ((fg * scale) as i32, (fb0 * scale) as i32, (fb1 * scale) as i32)
}

