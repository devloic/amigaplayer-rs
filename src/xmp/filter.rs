#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    #[cfg(all(target_os = "linux", target_env = "gnu"))]
    fn table_is_glibc_powf() {
        for c in 0..256 {
            let x = c as f32 * FREQ_PARAM_MULT + 0.25;
            assert_eq!(POW2_TABLE[c], 2.0f32.powf(x).to_bits(), "cutoff {c}");
        }
    }

    #[test]
    fn coefficients_match_libxmp() {
        // libxmp 4.7.4's libxmp_filter_setup (x86-64 glibc build)
        assert_eq!(filter_setup(48000, 255, 0), (906055, 5244989, -1956740));
        assert_eq!(filter_setup(48000, 100, 200), (21889, 8329355, -4156941));
        assert_eq!(filter_setup(44100, 0, 255), (1455, 8382025, -4189176));
        assert_eq!(filter_setup(8000, 254, 17), (3464818, 1080544, -351059));
    }
}
